def build() -> list[dict]:
    """Expand each fictional policy into three training phrasings and one holdout."""
    return [
        {"topic": topic, "question": question, "answer": answer, "facts": facts,
         "split": "validation" if index == 3 else "train"}
        for topic, answer, facts, questions in POLICIES
        for index, question in enumerate(questions)
    ]


if __name__ == "__main__":
    Path(__file__).with_name("faqs.jsonl").write_text(
        "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in build()),
        encoding="utf-8",
    )
